"""Generation of certificate PDFs using ReportLab.

Every generated PDF carries a SAMPLE watermark and a footer note,
because the approval, signature and seal are produced by a prototype system
and are not a valid government certificate.
"""
import math
from pathlib import Path

from reportlab.graphics import renderPDF
from reportlab.graphics.barcode.qr import QrCodeWidget
from reportlab.graphics.shapes import Drawing
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from ..catalog import get_certificate
from ..config import settings
from ..models import Application, Certificate

SAMPLE_NOTE = "Sample generated by prototype system – not for official use."

SAFFRON = colors.HexColor("#E8711A")
NAVY = colors.HexColor("#1E3A8A")
SEAL_BLUE = colors.HexColor("#2546A8")
GREY = colors.HexColor("#4B5563")

PAGE_WIDTH, PAGE_HEIGHT = A4
MARGIN = 18 * mm


def generate_certificate_pdf(app: Application, cert: Certificate, target: Path) -> None:
    cert_info = get_certificate(app.certificate_type) or {"name": "Certificate", "fields": []}
    pdf = canvas.Canvas(str(target), pagesize=A4)
    pdf.setTitle(f"{cert_info['name']} - {cert.certificate_number}")
    pdf.setSubject(SAMPLE_NOTE)

    _draw_border(pdf)
    _draw_watermark(pdf)
    y = _draw_header(pdf, cert_info["name"])
    y = _draw_numbers(pdf, app, cert, y)
    y = _draw_body(pdf, app, cert_info, y)
    _draw_signature_block(pdf, cert)
    _draw_seal(pdf, PAGE_WIDTH / 2 - 10 * mm, 62 * mm)
    _draw_qr(pdf, app, cert)
    _draw_footer(pdf)

    pdf.showPage()
    pdf.save()


def _draw_border(pdf: canvas.Canvas) -> None:
    pdf.setStrokeColor(NAVY)
    pdf.setLineWidth(2)
    pdf.rect(10 * mm, 10 * mm, PAGE_WIDTH - 20 * mm, PAGE_HEIGHT - 20 * mm)
    pdf.setStrokeColor(SAFFRON)
    pdf.setLineWidth(0.8)
    pdf.rect(12 * mm, 12 * mm, PAGE_WIDTH - 24 * mm, PAGE_HEIGHT - 24 * mm)


def _draw_watermark(pdf: canvas.Canvas) -> None:
    pdf.saveState()
    frame = pdf.beginPath()
    frame.rect(12 * mm, 12 * mm, PAGE_WIDTH - 24 * mm, PAGE_HEIGHT - 24 * mm)
    pdf.clipPath(frame, stroke=0, fill=0)
    pdf.translate(PAGE_WIDTH / 2, PAGE_HEIGHT / 2)
    pdf.rotate(40)
    # Small repeated marks across the whole page, so no area is unmarked.
    pdf.setFillColor(colors.Color(0.3, 0.35, 0.45, alpha=0.06))
    pdf.setFont("Helvetica-Bold", 22)
    for row in range(-9, 10):
        for col in range(-4, 5):
            pdf.drawCentredString(col * 52 * mm + (row % 2) * 26 * mm, row * 24 * mm, "SAMPLE")
    # One large mark in the centre.
    pdf.setFillColor(colors.Color(0.3, 0.35, 0.45, alpha=0.10))
    pdf.setFont("Helvetica-Bold", 96)
    pdf.drawCentredString(0, -30, "SAMPLE")
    pdf.restoreState()


def _draw_header(pdf: canvas.Canvas, title: str) -> float:
    top = PAGE_HEIGHT - 14 * mm
    pdf.setFillColor(SAFFRON)
    pdf.rect(12 * mm, top - 26 * mm, PAGE_WIDTH - 24 * mm, 26 * mm, stroke=0, fill=1)

    # Simple emblem placeholder: concentric circles with a star of lines.
    cx, cy = MARGIN + 10 * mm, top - 13 * mm
    pdf.setStrokeColor(colors.white)
    pdf.setFillColor(colors.white)
    pdf.setLineWidth(1.2)
    pdf.circle(cx, cy, 9 * mm, stroke=1, fill=0)
    pdf.circle(cx, cy, 2 * mm, stroke=0, fill=1)
    for i in range(24):
        angle = math.radians(i * 15)
        pdf.line(cx + 3 * mm * math.cos(angle), cy + 3 * mm * math.sin(angle),
                 cx + 8 * mm * math.cos(angle), cy + 8 * mm * math.sin(angle))

    pdf.setFillColor(colors.white)
    pdf.setFont("Helvetica-Bold", 16)
    pdf.drawCentredString(PAGE_WIDTH / 2 + 8 * mm, top - 10 * mm, "GOVERNMENT OF MAHARASHTRA")
    pdf.setFont("Helvetica", 10)
    pdf.drawCentredString(PAGE_WIDTH / 2 + 8 * mm, top - 16 * mm,
                          "Revenue Department  |  Citizen Certificate Portal")

    y = top - 40 * mm
    pdf.setFillColor(NAVY)
    pdf.setFont("Helvetica-Bold", 22)
    pdf.drawCentredString(PAGE_WIDTH / 2, y, title.upper())
    pdf.setStrokeColor(SAFFRON)
    pdf.setLineWidth(1.5)
    pdf.line(PAGE_WIDTH / 2 - 60 * mm, y - 4 * mm, PAGE_WIDTH / 2 + 60 * mm, y - 4 * mm)
    return y - 14 * mm


def _draw_numbers(pdf: canvas.Canvas, app: Application, cert: Certificate, y: float) -> float:
    pdf.setFillColor(colors.black)
    pdf.setFont("Helvetica", 10)
    pdf.drawString(MARGIN, y, f"Certificate No.: {cert.certificate_number}")
    pdf.drawRightString(PAGE_WIDTH - MARGIN, y, f"Issue Date: {cert.issued_at:%d-%m-%Y}")
    y -= 6 * mm
    pdf.drawString(MARGIN, y, f"Application Ref.: {app.reference}")
    pdf.drawRightString(PAGE_WIDTH - MARGIN, y, f"District: {app.district}")
    y -= 6 * mm
    validity = f"Valid Until: {cert.valid_until:%d-%m-%Y}" if cert.valid_until else "Validity: Permanent"
    pdf.setFont("Helvetica-Bold", 10)
    pdf.drawRightString(PAGE_WIDTH - MARGIN, y, validity)
    return y - 12 * mm


def _draw_body(pdf: canvas.Canvas, app: Application, cert_info: dict, y: float) -> float:
    pdf.setFont("Helvetica", 11)
    intro = (
        f"This is to certify that {app.full_name}, residing at {app.address}, "
        f"Taluka {app.taluka}, District {app.district}, PIN {app.pin_code}, "
        f"has been verified for the issue of this {cert_info['name']} "
        f"on the basis of the application and documents submitted."
    )
    y = _wrapped_text(pdf, intro, MARGIN, y, PAGE_WIDTH - 2 * MARGIN, 11, leading=15)
    y -= 6 * mm

    rows = [
        ("Full Name", app.full_name),
        ("Date of Birth", app.date_of_birth),
        ("Gender", app.gender),
        ("Mobile", app.mobile),
        ("Taluka / District", f"{app.taluka} / {app.district}"),
    ]
    for field in cert_info["fields"]:
        value = app.specific_data.get(field["name"])
        if value not in (None, ""):
            label = field["label"].replace(" (₹)", "")
            if field["type"] == "number" and "Income" in field["label"]:
                value = f"Rs. {float(value):,.0f}"
            rows.append((label, str(value)))

    pdf.setFont("Helvetica-Bold", 12)
    pdf.setFillColor(NAVY)
    pdf.drawString(MARGIN, y, "Certified Particulars")
    y -= 7 * mm
    for label, value in rows:
        pdf.setFillColor(GREY)
        pdf.setFont("Helvetica-Bold", 10)
        pdf.drawString(MARGIN + 2 * mm, y, label)
        pdf.setFillColor(colors.black)
        pdf.setFont("Helvetica", 10)
        pdf.drawString(MARGIN + 62 * mm, y, ": " + value[:70])
        y -= 6 * mm
    return y


def _wrapped_text(pdf, text, x, y, width, size, leading):
    words, line = text.split(), ""
    for word in words:
        candidate = f"{line} {word}".strip()
        if pdf.stringWidth(candidate, "Helvetica", size) > width:
            pdf.drawString(x, y, line)
            y -= leading
            line = word
        else:
            line = candidate
    if line:
        pdf.drawString(x, y, line)
        y -= leading
    return y


def _draw_signature_block(pdf: canvas.Canvas, cert: Certificate) -> None:
    x = PAGE_WIDTH - MARGIN - 60 * mm
    y = 70 * mm
    # Mock handwritten signature drawn as a few curves.
    pdf.setStrokeColor(NAVY)
    pdf.setLineWidth(1.3)
    path = pdf.beginPath()
    path.moveTo(x + 5 * mm, y)
    path.curveTo(x + 12 * mm, y + 12 * mm, x + 16 * mm, y - 6 * mm, x + 22 * mm, y + 5 * mm)
    path.curveTo(x + 27 * mm, y + 14 * mm, x + 30 * mm, y - 4 * mm, x + 38 * mm, y + 3 * mm)
    path.curveTo(x + 44 * mm, y + 8 * mm, x + 48 * mm, y - 2 * mm, x + 55 * mm, y + 2 * mm)
    pdf.drawPath(path, stroke=1, fill=0)
    pdf.line(x + 8 * mm, y - 3 * mm, x + 50 * mm, y - 1 * mm)

    pdf.setFillColor(colors.black)
    pdf.setFont("Helvetica-Bold", 10)
    pdf.drawCentredString(x + 30 * mm, y - 10 * mm, cert.officer_name)
    pdf.setFont("Helvetica", 9)
    pdf.drawCentredString(x + 30 * mm, y - 15 * mm, cert.officer_designation)
    pdf.drawCentredString(x + 30 * mm, y - 20 * mm, "Issuing Authority")


def _draw_seal(pdf: canvas.Canvas, cx: float, cy: float) -> None:
    radius = 17 * mm
    pdf.saveState()
    pdf.setStrokeColor(SEAL_BLUE)
    pdf.setFillColor(SEAL_BLUE)
    pdf.setLineWidth(1.5)
    pdf.circle(cx, cy, radius, stroke=1, fill=0)
    pdf.setLineWidth(0.8)
    pdf.circle(cx, cy, radius - 5 * mm, stroke=1, fill=0)

    text = "OFFICE OF THE TAHSILDAR * MAHARASHTRA * "
    pdf.setFont("Helvetica-Bold", 7)
    step = 360 / len(text)
    for i, char in enumerate(text):
        angle = 90 - i * step
        rad = math.radians(angle)
        pdf.saveState()
        pdf.translate(cx + (radius - 3.4 * mm) * math.cos(rad),
                      cy + (radius - 3.4 * mm) * math.sin(rad))
        pdf.rotate(angle - 90)
        pdf.drawCentredString(0, 0, char)
        pdf.restoreState()

    pdf.setFont("Helvetica-Bold", 8)
    pdf.drawCentredString(cx, cy + 1.5 * mm, "OFFICE")
    pdf.drawCentredString(cx, cy - 3 * mm, "SEAL")
    pdf.restoreState()


def _draw_qr(pdf: canvas.Canvas, app: Application, cert: Certificate) -> None:
    payload = (
        f"SAMPLE | {cert.certificate_number} | {app.reference} | "
        f"{settings.public_base_url}/track.html?ref={app.reference}"
    )
    widget = QrCodeWidget(payload)
    x1, y1, x2, y2 = widget.getBounds()
    size = 30 * mm
    drawing = Drawing(size, size, transform=[size / (x2 - x1), 0, 0, size / (y2 - y1), 0, 0])
    drawing.add(widget)
    renderPDF.draw(drawing, pdf, MARGIN, 45 * mm)
    pdf.setFont("Helvetica", 7)
    pdf.setFillColor(GREY)
    pdf.drawString(MARGIN, 42 * mm, "Scan to view application status")


def _draw_footer(pdf: canvas.Canvas) -> None:
    pdf.setStrokeColor(colors.HexColor("#CBD5E1"))
    pdf.setLineWidth(0.5)
    pdf.line(MARGIN, 26 * mm, PAGE_WIDTH - MARGIN, 26 * mm)
    pdf.setFillColor(GREY)
    pdf.setFont("Helvetica", 8)
    pdf.drawCentredString(
        PAGE_WIDTH / 2, 21 * mm,
        "This certificate was generated electronically by the Citizen Certificate Portal.",
    )
    pdf.setFont("Helvetica-Oblique", 7.5)
    pdf.drawCentredString(PAGE_WIDTH / 2, 16.5 * mm, SAMPLE_NOTE)
